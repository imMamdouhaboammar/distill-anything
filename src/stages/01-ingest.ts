import { existsSync, mkdtempSync, readFileSync, rmSync, statSync } from "node:fs";
import { tmpdir } from "node:os";
import { basename, extname, join, relative, resolve, sep } from "node:path";
import fg from "fast-glob";
import ignore from "ignore";
import type { MaturityClassification, RepoProfile } from "../schemas/repo-profile";

export interface DiscoveredFile {
  relPath: string;
  absPath: string;
  language: string;
  isTest: boolean;
  loc: number;
  content: string;
}

export interface IngestResult {
  repoRoot: string;
  analysisRoot: string;
  profile: RepoProfile;
  files: DiscoveredFile[];
  isGitRepo: boolean;
  cleanup: () => void;
}

const IGNORED_DIRS = [
  ".git",
  "node_modules",
  "dist",
  "build",
  "target",
  ".next",
  "__pycache__",
  ".venv",
  "vendor",
  "third_party",
];

const IGNORED_FILES = new Set([
  "package-lock.json",
  "bun.lock",
  "bun.lockb",
  "yarn.lock",
  "pnpm-lock.yaml",
  "Cargo.lock",
  "go.sum",
  "poetry.lock",
]);

const BINARY_OR_BUNDLE_EXTS = new Set([
  ".png",
  ".jpg",
  ".jpeg",
  ".gif",
  ".webp",
  ".svg",
  ".ico",
  ".woff",
  ".woff2",
  ".ttf",
  ".eot",
  ".wasm",
  ".pdf",
  ".onnx",
  ".safetensors",
  ".bin",
  ".map",
  ".zip",
  ".tar",
  ".gz",
]);

const MAX_FILE_BYTES = 250 * 1024;
const MAX_FILE_LINES = 3000;

const EXT_TO_LANG: Record<string, string> = {
  ".ts": "typescript",
  ".mts": "typescript",
  ".cts": "typescript",
  ".tsx": "tsx",
  ".js": "javascript",
  ".mjs": "javascript",
  ".cjs": "javascript",
  ".jsx": "javascript",
  ".py": "python",
  ".rs": "rust",
  ".go": "go",
  ".cpp": "cpp",
  ".cc": "cpp",
  ".cxx": "cpp",
  ".hpp": "cpp",
  ".h": "cpp",
  ".c": "cpp",
  ".md": "markdown",
};

export function isRemoteSource(source: string): boolean {
  return /^(https?:\/\/|git@|ssh:\/\/)/.test(source);
}

export function toKebabSlug(raw: string): string {
  const cleaned = raw
    .replace(/\.git$/, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
  return cleaned || "distilled-repo";
}

export function isTestFilePath(relPath: string): boolean {
  const lower = relPath.toLowerCase();
  const base = basename(lower);
  if (
    lower.includes("/tests/") ||
    lower.includes("/__tests__/") ||
    lower.startsWith("tests/") ||
    lower.startsWith("test/") ||
    lower.includes("/test/")
  ) {
    return true;
  }
  return (
    /\.(test|spec)\.[a-z0-9]+$/.test(base) ||
    /_test\.go$/.test(base) ||
    /^test_.*\.py$/.test(base) ||
    /_test\.py$/.test(base) ||
    /_test\.rs$/.test(base)
  );
}

function isGeneratedStub(content: string): boolean {
  const firstFive = content.split("\n", 5).join("\n");
  return (
    firstFive.includes("DO NOT EDIT") ||
    firstFive.includes("@generated") ||
    firstFive.includes("Code generated by")
  );
}

async function runGitAsync(
  args: string[],
  cwd: string,
  onSpawn?: (proc: ReturnType<typeof Bun.spawn>) => void,
): Promise<{ ok: boolean; stdout: string; stderr: string }> {
  const proc = Bun.spawn(["git", ...args], {
    cwd,
    stdout: "pipe",
    stderr: "pipe",
  });
  onSpawn?.(proc);
  const exitCode = await proc.exited;
  const stdout = await new Response(proc.stdout).text();
  const stderr = await new Response(proc.stderr).text();
  return {
    ok: exitCode === 0,
    stdout: stdout.trim(),
    stderr: stderr.trim(),
  };
}

function checkStrictTyping(analysisRoot: string, repoRoot: string, primaryLanguage: string): boolean {
  if (["rust", "go", "cpp"].includes(primaryLanguage)) return true;
  for (const dir of [analysisRoot, repoRoot]) {
    const tsconfig = join(dir, "tsconfig.json");
    if (existsSync(tsconfig)) {
      try {
        const raw = readFileSync(tsconfig, "utf8");
        if (/"strict"\s*:\s*true/.test(raw)) return true;
      } catch {
        // ignore unreadable tsconfig
      }
    }
    if (existsSync(join(dir, "mypy.ini")) || existsSync(join(dir, "pyrightconfig.json"))) {
      return true;
    }
  }
  return false;
}

export async function ingestRepository(options: {
  source: string;
  subpath: string;
  gitDepth: number;
  noGit: boolean;
  nameOverride?: string | undefined;
}): Promise<IngestResult> {
  let repoRoot: string;
  let tempDir: string | null = null;
  let activeCloneProc: ReturnType<typeof Bun.spawn> | null = null;

  const cleanupTemp = () => {
    if (activeCloneProc) {
      try {
        activeCloneProc.kill("SIGKILL");
      } catch {
        // ignore if already exited
      }
      activeCloneProc = null;
    }
    if (tempDir && existsSync(tempDir)) {
      rmSync(tempDir, { recursive: true, force: true });
      tempDir = null;
    }
  };

  const onSignal = (sig: NodeJS.Signals) => {
    cleanupTemp();
    process.exit(sig === "SIGINT" ? 130 : 143);
  };

  if (isRemoteSource(options.source)) {
    tempDir = mkdtempSync(join(tmpdir(), "distill-anything-"));
    process.on("SIGINT", onSignal);
    process.on("SIGTERM", onSignal);
    const clone = await runGitAsync(
      ["clone", "--depth", String(options.gitDepth), "--filter=blob:none", "--no-tags", options.source, tempDir],
      tmpdir(),
      (proc) => {
        activeCloneProc = proc;
      },
    );
    activeCloneProc = null;
    if (!clone.ok) {
      process.off("SIGINT", onSignal);
      process.off("SIGTERM", onSignal);
      cleanupTemp();
      throw new Error(`Failed to clone repository "${options.source}": ${clone.stderr}`);
    }
    repoRoot = tempDir;
  } else {
    repoRoot = resolve(options.source);
    if (!existsSync(repoRoot) || !statSync(repoRoot).isDirectory()) {
      throw new Error(`Source directory does not exist: ${repoRoot}`);
    }
  }

  const cleanup = () => {
    process.off("SIGINT", onSignal);
    process.off("SIGTERM", onSignal);
    cleanupTemp();
  };

  try {
    const analysisRoot = resolve(repoRoot, options.subpath);
    const normalizedRoot = repoRoot.endsWith(sep) ? repoRoot : `${repoRoot}${sep}`;
    if (analysisRoot !== repoRoot && !analysisRoot.startsWith(normalizedRoot)) {
      throw new Error(`Invalid --subpath "${options.subpath}": escapes repository root.`);
    }
    if (!existsSync(analysisRoot) || !statSync(analysisRoot).isDirectory()) {
      throw new Error(`Subpath does not exist inside repository: ${options.subpath}`);
    }

    const isGitRepo = !options.noGit && existsSync(join(repoRoot, ".git"));
    let commitSha: string | null = null;
    if (isGitRepo) {
      const head = await runGitAsync(["rev-parse", "HEAD"], repoRoot);
      if (head.ok && head.stdout) {
        commitSha = head.stdout;
      }
    }

    const ig = ignore();
    ig.add(IGNORED_DIRS.map((d) => `${d}/`));
    for (const ignoreFile of [join(repoRoot, ".gitignore"), join(analysisRoot, ".gitignore"), join(analysisRoot, ".distillignore")]) {
      if (existsSync(ignoreFile)) {
        ig.add(readFileSync(ignoreFile, "utf8"));
      }
    }

    const candidatePaths = await fg(["**/*"], {
      cwd: analysisRoot,
      onlyFiles: true,
      dot: true,
      followSymbolicLinks: false,
      ignore: IGNORED_DIRS.map((d) => `**/${d}/**`),
    });

    const files: DiscoveredFile[] = [];
    const skippedOversizedFiles: string[] = [];
    const langCounts = new Map<string, { fileCount: number; loc: number }>();
    let totalMarkers = 0;
    let totalCodeLoc = 0;
    let testFileCount = 0;
    let sourceFileCount = 0;
    let hasBenchmarks = false;
    let hasNotebooksOrExperiments = false;

    for (const relPath of candidatePaths) {
      if (ig.ignores(relPath)) continue;
      const base = basename(relPath);
      if (IGNORED_FILES.has(base)) continue;
      if (base.endsWith(".min.js") || base.endsWith(".bundle.js")) continue;

      const ext = extname(base).toLowerCase();
      if (BINARY_OR_BUNDLE_EXTS.has(ext)) continue;

      if (
        /(^|\/)(bench|benches|benchmarks)\//.test(relPath) ||
        /\.bench\.[a-z0-9]+$/.test(base)
      ) {
        hasBenchmarks = true;
      }
      if (/(^|\/)(notebooks|paper|experiments)\//.test(relPath) || ext === ".ipynb") {
        hasNotebooksOrExperiments = true;
      }

      const language = EXT_TO_LANG[ext];
      if (!language) continue;

      const absPath = join(analysisRoot, relPath);
      const stat = statSync(absPath);
      if (stat.size > MAX_FILE_BYTES) {
        skippedOversizedFiles.push(relPath);
        continue;
      }

      const content = readFileSync(absPath, "utf8");
      if (content.includes("\u0000")) continue;

      const lines = content.split("\n");
      if (lines.length > MAX_FILE_LINES) {
        skippedOversizedFiles.push(relPath);
        continue;
      }
      if (language !== "markdown" && isGeneratedStub(content)) continue;

      const isTest = language !== "markdown" && isTestFilePath(relPath);
      const loc = lines.length;

      files.push({ relPath, absPath, language, isTest, loc, content });

      if (language !== "markdown") {
        const entry = langCounts.get(language) ?? { fileCount: 0, loc: 0 };
        entry.fileCount += 1;
        entry.loc += loc;
        langCounts.set(language, entry);

        totalCodeLoc += loc;
        if (isTest) testFileCount += 1;
        else sourceFileCount += 1;

        const markerMatches = content.match(/\b(TODO|FIXME|HACK|XXX)\b/g);
        if (markerMatches) totalMarkers += markerMatches.length;
      }
    }

    const languages = Array.from(langCounts.entries())
      .map(([language, stats]) => ({
        language,
        fileCount: stats.fileCount,
        loc: stats.loc,
        sharePercent: totalCodeLoc > 0 ? Number(((stats.loc / totalCodeLoc) * 100).toFixed(1)) : 0,
      }))
      .sort((a, b) => b.loc - a.loc);

    if (languages.length === 0) {
      languages.push({ language: "unknown", fileCount: files.length, loc: 0, sharePercent: 100 });
    }

    const primaryLanguage = languages[0]?.language ?? "unknown";
    const hasCiWorkflows =
      existsSync(join(repoRoot, ".github/workflows")) ||
      existsSync(join(repoRoot, ".gitlab-ci.yml")) ||
      existsSync(join(repoRoot, "Makefile"));
    const hasStrictTyping = checkStrictTyping(analysisRoot, repoRoot, primaryLanguage);
    const testToSourceRatio =
      sourceFileCount > 0 ? Number((testFileCount / sourceFileCount).toFixed(2)) : 0;
    const experimentalMarkersPerKloc =
      totalCodeLoc > 0 ? Number(((totalMarkers / totalCodeLoc) * 1000).toFixed(2)) : 0;

    let classification: MaturityClassification = "hybrid";
    if (hasCiWorkflows && testFileCount > 0 && experimentalMarkersPerKloc < 8 && !hasNotebooksOrExperiments) {
      classification = "production";
    } else if (hasNotebooksOrExperiments || (!hasCiWorkflows && testFileCount === 0)) {
      classification = "research_prototype";
    }

    const derivedName = isRemoteSource(options.source)
      ? basename(options.source).replace(/\.git$/, "")
      : basename(repoRoot);
    const skillSlug = options.nameOverride ?? toKebabSlug(derivedName);

    const profile: RepoProfile = {
      source: options.source,
      repoName: derivedName,
      skillSlug,
      commitSha,
      subpath: relative(repoRoot, analysisRoot) || ".",
      analyzedAt: new Date().toISOString(),
      primaryLanguage,
      languages,
      totalFilesScanned: files.length,
      skippedOversizedFiles,
      maturity: {
        classification,
        hasCiWorkflows,
        hasBenchmarks,
        hasStrictTyping,
        testToSourceRatio,
        experimentalMarkersPerKloc,
      },
    };

    return { repoRoot, analysisRoot, profile, files, isGitRepo, cleanup };
  } catch (err) {
    cleanup();
    throw err;
  }
}
