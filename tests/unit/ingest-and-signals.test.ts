import { afterAll, beforeAll, describe, expect, it } from "bun:test";
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { ingestRepository } from "../../src/stages/01-ingest";
import { buildSignalBundle } from "../../src/stages/02-signals/bundler";
import { mineHighSignalCommits } from "../../src/stages/02-signals/git-miner";

let repoDir: string;

function git(args: string[], cwd: string): void {
  const res = Bun.spawnSync(["git", ...args], { cwd, stdout: "pipe", stderr: "pipe" });
  if (res.exitCode !== 0) {
    throw new Error(`git ${args.join(" ")} failed: ${new TextDecoder().decode(res.stderr)}`);
  }
}

beforeAll(() => {
  repoDir = mkdtempSync(join(tmpdir(), "distill-repo-"));
  mkdirSync(join(repoDir, "src"), { recursive: true });
  mkdirSync(join(repoDir, "tests"), { recursive: true });

  writeFileSync(
    join(repoDir, "tsconfig.json"),
    JSON.stringify({ compilerOptions: { strict: true } }),
  );
  writeFileSync(
    join(repoDir, "src/core.ts"),
    [
      "export interface Frame { id: number; payload: Uint8Array; }",
      "export class BackpressureQueue {",
      "  private ctrl = new AbortController();",
      "  enqueue(f: Frame): boolean { return f.id > 0; }",
      "}",
    ].join("\n"),
  );
  writeFileSync(
    join(repoDir, "src/worker.ts"),
    [
      "import { BackpressureQueue, type Frame } from './core';",
      "export function runWorker(q: BackpressureQueue, f: Frame) {",
      "  return q.enqueue(f);",
      "}",
    ].join("\n"),
  );
  writeFileSync(
    join(repoDir, "src/leaf.ts"),
    "export const VERSION = '1.0.0';\n",
  );
  // Generated & noise files that MUST be filtered out
  writeFileSync(
    join(repoDir, "src/generated.ts"),
    "// Code generated by protoc-gen-ts. DO NOT EDIT.\nexport const stub = true;\n",
  );
  writeFileSync(join(repoDir, "src/vendor.min.js"), "var a=1;console.log(a);\n");
  writeFileSync(join(repoDir, "package-lock.json"), "{}\n");

  // Large file > 4,000 tokens to test line-preserving smart truncation
  const bigLines = [
    "export interface LargeConfig { id: number; }",
    ...Array.from({ length: 600 }, (_, i) => `function helper${i}(n: number): number { return n + ${i}; }`),
  ];
  writeFileSync(join(repoDir, "src/large.ts"), bigLines.join("\n"));

  writeFileSync(
    join(repoDir, "tests/core.test.ts"),
    [
      "import { BackpressureQueue } from '../src/core';",
      "test('handles overflow and abort boundary', () => {",
      "  const q = new BackpressureQueue();",
      "  expect(q.enqueue({ id: 1, payload: new Uint8Array(0) })).toBe(true);",
      "});",
    ].join("\n"),
  );
  writeFileSync(join(repoDir, "README.md"), "# Demo Engine\n\n## Architecture\nUses BackpressureQueue.\n");

  // Initialize git repo for commit mining tests
  git(["init"], repoDir);
  git(["config", "user.email", "test@example.com"], repoDir);
  git(["config", "user.name", "Test User"], repoDir);
  git(["add", "."], repoDir);
  git(["commit", "-m", "chore: initial commit"], repoDir);

  // Commit 1: High-signal perf commit with explanatory body
  writeFileSync(
    join(repoDir, "src/core.ts"),
    [
      "export interface Frame { id: number; payload: Uint8Array; }",
      "export class BackpressureQueue {",
      "  private ctrl = new AbortController();",
      "  private pool = new WeakMap<object, Frame>();",
      "  enqueue(f: Frame): boolean { return f.id > 0; }",
      "}",
    ].join("\n"),
  );
  git(["add", "src/core.ts"], repoDir);
  git(
    [
      "commit",
      "-m",
      "perf: avoid lock contention in BackpressureQueue",
      "-m",
      "Replaced global array lock with WeakMap slot tracking to eliminate tail-latency spikes under concurrent producers.",
    ],
    repoDir,
  );

  // Commit 2: Version bump commit (must be excluded)
  writeFileSync(join(repoDir, "src/leaf.ts"), "export const VERSION = '1.0.1';\n");
  git(["add", "src/leaf.ts"], repoDir);
  git(["commit", "-m", "chore(release): bump version to 1.0.1"], repoDir);
});

afterAll(() => {
  rmSync(repoDir, { recursive: true, force: true });
});

describe("Ingest & SignalBundler", () => {
  it("filters generated/minified/lockfiles and computes AST fan-in scoring", async () => {
    const ingest = await ingestRepository({
      source: repoDir,
      subpath: ".",
      gitDepth: 50,
      noGit: false,
    });
    try {
      const paths = ingest.files.map((f) => f.relPath);
      expect(paths).not.toContain("src/generated.ts");
      expect(paths).not.toContain("src/vendor.min.js");
      expect(paths).not.toContain("package-lock.json");
      expect(ingest.profile.primaryLanguage).toBe("typescript");
      expect(ingest.profile.maturity.hasStrictTyping).toBe(true);

      const bundle = await buildSignalBundle({
        ingest,
        maxFiles: 10,
        maxCommits: 5,
        gitDepth: 50,
      });

      expect(bundle.totalTokens).toBeLessThanOrEqual(60_000);
      const coreFile = bundle.files.find((f) => f.path === "src/core.ts");
      const leafFile = bundle.files.find((f) => f.path === "src/leaf.ts");
      expect(coreFile).toBeDefined();
      expect(coreFile?.fanIn).toBe(1);
      expect(coreFile!.score).toBeGreaterThan(leafFile?.score ?? 0);
      expect(coreFile?.numberedContent).toContain("0001 | export interface Frame");
    } finally {
      ingest.cleanup();
    }
  });

  it("preserves original line numbers during smart truncation", async () => {
    const ingest = await ingestRepository({
      source: repoDir,
      subpath: ".",
      gitDepth: 50,
      noGit: true,
    });
    try {
      const bundle = await buildSignalBundle({
        ingest,
        maxFiles: 10,
        maxCommits: 0,
        gitDepth: 50,
      });
      const largeFile = bundle.files.find((f) => f.path === "src/large.ts");
      expect(largeFile).toBeDefined();
      expect(largeFile?.truncated).toBe(true);
      expect(largeFile?.numberedContent).toContain("/* [elided lines");
      expect(largeFile?.numberedContent).toContain("0001 | export interface LargeConfig");
    } finally {
      ingest.cleanup();
    }
  });

  it("mines high-signal perf commits and excludes release bumps", () => {
    const commits = mineHighSignalCommits({
      repoRoot: repoDir,
      gitDepth: 50,
      maxCommits: 10,
      tokenBudget: 15_000,
      coreFilePaths: new Set(["src/core.ts"]),
    });
    expect(commits).toHaveLength(1);
    expect(commits[0]?.subject).toContain("perf: avoid lock contention");
  });
});
